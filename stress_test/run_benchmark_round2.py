"""
Competitive benchmark + self-improvement protocol -- ROUND 2.

See claude/ANTI_CASSIOPEIA_COMPETITIVE_BENCHMARK_PROTOCOL.md for the full,
locked spec this follows, and run_benchmark_round1.py for round 1's own
(hand-picked, 9-claim) implementation this script is closely modeled on.
This round is bigger and differently sourced: 102 claims, loaded from
`stress_test/claims/external_generated/claims_round2_verified.json` --
externally generated by three different AI tools (ChatGPT, Gemini,
Perplexity) and then independently verified against real primary/
secondary sources by this project (see that file's own sibling README.md
and `verified_category*.json` files for the verification methodology;
NOT re-verified again here). `verified_ground_truth` is the real,
independently-checked ground truth used for scoring; `suggested_ground_truth`
is only the GENERATING AI's own unverified guess and is never used to score
anything here.

TWO deliberate differences from round 1, both called out explicitly in this
round's own task brief:

1. DOMAIN RENAME. Round 1 imported `anticassiopeia.domains.research_web`
   and pulled `RECOMMENDED_STANCE_MODEL` from there. That module is now a
   deprecated backward-compat SHIM (`anticassiopeia/domains/research_web.py`
   -- read its own docstring; left alone deliberately, not touched here).
   The real, current adapter is `anticassiopeia.domains.searchlight`
   (`SearchlightAdapter`), and `RECOMMENDED_STANCE_MODEL` now lives in
   `anticassiopeia.retrieval.stance` -- both imported from their real,
   current locations below, for THIS script's own real-engine run.

   This surfaces a real, pre-existing wiring wrinkle, not something this
   script papers over: `stress_test/`'s OTHER harness scripts
   (`run_test1.py`'s `build_engine()`, and every `run_test3_*.py` that calls
   it) were never updated for the rename -- they still construct their
   engine with the adapter registered under the OLD domain key
   `"research_web"`, and `run_test3_nebius_agent.py`'s own
   `_PROPOSE_ONLY_DOMAINS` filter and `run_test3_generic_rag.py`'s own
   domain dispatch both still match on the literal string `"research_web"`,
   not `"searchlight"`. Per this round's own instruction to REUSE those
   functions exactly as they are (not reimplement or edit them), this
   script keeps each claim's canonical record using the real, current
   domain name (`"searchlight"`, used for this script's OWN real-engine
   run and for every report/scorecard field) but hands the UNCHANGED
   competitor-harness functions a domain-patched COPY of each claim
   (`domain: "research_web"`) purely so their own pre-existing, unedited
   domain-matching logic still does what it was built to do. This is a
   data-shape adaptation at the call boundary, not a change to any
   harness function's logic -- see `_for_competitor_harness()` below.

   A SEPARATE, already-documented consequence of this same rename, found
   while reading (not newly introduced here): `research_web.py`'s own
   docstring states that `run_test3_nebius_agent.py`'s monkeypatch of
   `anticassiopeia.domains.research_web.verify_proposal` now silently
   no-ops, because that monkeypatch targets the SHIM's module namespace,
   not `searchlight.py`'s real one (the module where the real adapter's
   code actually looks the name up) -- so "nebius-agent" can no longer
   actually skip the independent verify step for `searchlight`-routed
   claims the way it could pre-rename. Not fixed here (fixing it means
   editing `stress_test/`, explicitly out of scope for the rename, per
   that module's own docstring) -- reported honestly in this round's own
   report instead, as the protocol's own house style requires.

2. CATEGORY 7 IS NOT EXEMPTED THIS ROUND. Round 1's category 7 claims were
   sourced FROM one specific, already-fetched fact-check verdict (Full
   Fact), so there was no independent "competitor" to run against --
   running Perplexity/Tavily+Gemini/etc. against a claim whose ground
   truth came from a single already-read article would have been circular
   in a different way than intended. Round 2's category 7 claims are
   different: the generating AI only GUESSED a fact-checking org had
   probably covered a given claim; ground truth was established by
   genuinely independent research (see each entry's own
   `verification_sources`), not by reading one specific pre-selected
   verdict. There is therefore no reason to exempt category 7 this round
   -- ALL 102 claims, across all 7 categories, run through the real engine
   AND all 5 competitor variants, with no exception.

COMPETITOR SCOPE: all 102 claims run through the real engine and all 5
competitor variants (bare model, nebius-agent, generic RAG, Perplexity,
Tavily+Gemini) -- reusing the existing harness functions directly, exactly
as round 1 did; nothing here reimplements retrieval, propose(), judge_stance(),
or any competitor's calling code.

BUDGET: see the dry-run section of this round's own report
(BENCHMARK_ROUND2_REPORT.md) for the small-slice sanity check this script's
own `--mode dryrun` performed before the full run was authorized. Nebius
sub-cap and Anti-Cassiopeia's own budget are both set generously below the
dry-run-extrapolated total but nowhere near the project's $20 cap -- see
the constants below and the report for the real, measured numbers.

Usage:
    PYTHONPATH=. python3 stress_test/run_benchmark_round2.py --mode dryrun
    PYTHONPATH=. python3 stress_test/run_benchmark_round2.py --mode full
"""

from __future__ import annotations

import argparse
import asyncio
import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).parent.parent
sys.path.insert(0, str(REPO_ROOT))
sys.path.insert(0, str(Path(__file__).parent))

# Same fix round 1's own script applied (see its own top-of-file comment for
# the full finding): load .env into the REAL process environment before
# anything downstream (searchlight.py's _tavily_search(), which reads
# os.environ.get("TAVILY_API_KEY") directly) has a chance to read it.
from dotenv import load_dotenv  # noqa: E402
load_dotenv(REPO_ROOT / ".env", override=False)

from anticassiopeia.core import Claim, VerificationEngine  # noqa: E402
from anticassiopeia.domains.searchlight import SearchlightAdapter  # noqa: E402
from anticassiopeia.retrieval.stance import RECOMMENDED_STANCE_MODEL  # noqa: E402
from instrumented_client import InstrumentedNebiusClient, NEMOTRON_PRICING_PER_M, UsageTracker  # noqa: E402
from run_test1 import classify  # noqa: E402
from run_test3_bare_model import run_bare_model_batch  # noqa: E402
from run_test3_generic_rag import run_generic_rag_batch  # noqa: E402
from run_test3_nebius_agent import run_nebius_agent_batch  # noqa: E402
from run_test3_perplexity import run_perplexity_batch  # noqa: E402
from run_test3_tavily_gemini import run_tavily_gemini_batch  # noqa: E402

RESULTS_DIR = REPO_ROOT / "stress_test/results"
CLAIMS_PATH = REPO_ROOT / "stress_test/claims/external_generated/claims_round2_verified.json"
ROUND2_RAW_PATH = RESULTS_DIR / "benchmark_round2_raw.json"

# Generous headroom over the dry-run-measured per-claim cost (see the
# report), nowhere near the project's $20 cap. Anti-Cassiopeia's own run
# uses TWO instrumented clients (propose on gpt-oss-120b, stance-judging on
# RECOMMENDED_STANCE_MODEL/Nemotron Ultra) sharing one tracker/budget, same
# pattern as round 1.
ROUND2_AC_BUDGET_USD = 3.00
ROUND2_NEBIUS_COMPETITOR_SUBCAP_USD = 3.00


def load_claims() -> list[dict]:
    with open(CLAIMS_PATH) as f:
        raw = json.load(f)
    claims = []
    for entry in raw:
        claims.append({
            "claim_id": entry["id"],
            "category": entry["category"],
            "generated_by": entry["generated_by"],
            "domain": "searchlight",
            "tier": 1,
            "claim_payload": {
                "text": entry["claim"],
                "domain": "searchlight",
                "context": {},
            },
            "ground_truth_verdict": entry["verified_ground_truth"],
            "ground_truth_note": entry["verification_notes"],
            "ground_truth_sources": entry["verification_sources"],
            "verification_confidence": entry["verification_confidence"],
        })
    return claims


def _for_competitor_harness(claims: list[dict]) -> list[dict]:
    """Domain-patched COPY for the pre-existing, un-renamed competitor
    harness functions -- see this module's own docstring, point 1, for why
    this exists and what it does NOT change (no harness logic is touched;
    only the `domain` field each claim dict carries, so build_engine()'s
    still-"research_web"-keyed adapter registration and
    nebius_agent/generic_rag's still-"research_web"-matching dispatch both
    keep working exactly as they always have)."""
    patched = []
    for c in claims:
        c2 = dict(c)
        c2["domain"] = "research_web"
        c2["claim_payload"] = {**c["claim_payload"], "domain": "research_web"}
        patched.append(c2)
    return patched


async def run_anti_cassiopeia(claims: list[dict]) -> tuple[list[dict], UsageTracker]:
    """Real engine, real adapter, exactly as default_domains() builds it:
    propose() on gpt-oss-120b, judge_stance() on
    RECOMMENDED_STANCE_MODEL/Nemotron Ultra. Only substitution:
    InstrumentedNebiusClient in place of the production
    NebiusTokenFactoryClient, for real cost tracking -- same duck-typed
    injection point every other harness script in this directory uses."""
    tracker = UsageTracker()
    propose_client = InstrumentedNebiusClient(tracker, model="openai/gpt-oss-120b", budget_usd=ROUND2_AC_BUDGET_USD)
    stance_in, stance_out = NEMOTRON_PRICING_PER_M[RECOMMENDED_STANCE_MODEL]
    stance_client = InstrumentedNebiusClient(
        tracker, model=RECOMMENDED_STANCE_MODEL, input_cost_per_m=stance_in, output_cost_per_m=stance_out,
        budget_usd=ROUND2_AC_BUDGET_USD,
    )
    adapter = SearchlightAdapter(client=propose_client, stance_client=stance_client)
    engine = VerificationEngine(domains={"searchlight": adapter})

    results = []
    for c in claims:
        tracker.set_domain("searchlight")
        claim = Claim(**c["claim_payload"])
        try:
            verdict = await engine.verify(claim)
            predicted = verdict.state.value
            confidence = verdict.confidence
            evidence = [{"source": e.source, "stance": e.stance, "snippet": e.snippet[:300]} for e in verdict.evidence]
            reasoning = verdict.reasoning
            missing = verdict.missing
            error = None
        except Exception as exc:  # noqa: BLE001 -- a crash IS a result worth recording
            predicted = "CRASH"
            confidence = None
            evidence, reasoning, missing = [], [], []
            error = f"{type(exc).__name__}: {exc}"
        severity = "crash" if predicted == "CRASH" else classify(predicted, c["ground_truth_verdict"])
        results.append({
            "claim_id": c["claim_id"],
            "category": c["category"],
            "generated_by": c["generated_by"],
            "predicted_verdict": predicted,
            "severity": severity,
            "confidence": confidence,
            "ground_truth_verdict": c["ground_truth_verdict"],
            "evidence": evidence,
            "reasoning": reasoning,
            "missing": missing,
            "error": error,
        })
        print(
            f"[anti-cassiopeia] {c['claim_id']:18s} cat={c['category']} predicted={predicted:13s} "
            f"truth={c['ground_truth_verdict']:13s} severity={severity:17s} confidence={confidence}"
        )
    return results, tracker


def _score_row(predicted: str, ground_truth: str) -> str:
    return classify(predicted, ground_truth)


async def main(mode: str) -> None:
    all_claims = load_claims()
    if mode == "dryrun":
        claims = all_claims[:5]
        tag = "round2-dryrun"
        raw_out = RESULTS_DIR / "benchmark_round2_dryrun_raw.json"
    else:
        claims = all_claims
        tag = "round2"
        raw_out = ROUND2_RAW_PATH

    competitor_claims = _for_competitor_harness(claims)

    print("=" * 90)
    print(f"COMPETITIVE BENCHMARK ROUND 2 ({mode}) -- {len(claims)} claims, all run through the real "
          f"engine and all 5 competitor variants (no category exemption this round).")
    print("=" * 90)

    ac_results, ac_tracker = await run_anti_cassiopeia(claims)

    print("\n--- Variant 2: bare model ---")
    nebius_tracker = UsageTracker()
    bare_model_results = await run_bare_model_batch(
        competitor_claims, tag=tag, tracker=nebius_tracker, budget_usd=ROUND2_NEBIUS_COMPETITOR_SUBCAP_USD,
        raw_results_path=RESULTS_DIR / f"benchmark_{tag}_bare_model_raw.jsonl",
    )

    print("\n--- Variant 3: Nebius-agent ---")
    nebius_agent_results = await run_nebius_agent_batch(
        competitor_claims, tag=tag, tracker=nebius_tracker, budget_usd=ROUND2_NEBIUS_COMPETITOR_SUBCAP_USD,
        raw_results_path=RESULTS_DIR / f"benchmark_{tag}_nebius_agent_raw.jsonl",
    )

    print("\n--- Variant 4: generic RAG ---")
    generic_rag_results = await run_generic_rag_batch(
        competitor_claims, tag=tag, tracker=nebius_tracker, budget_usd=ROUND2_NEBIUS_COMPETITOR_SUBCAP_USD,
        raw_results_path=RESULTS_DIR / f"benchmark_{tag}_generic_rag_raw.jsonl",
    )

    print("\n--- Variant 5: Perplexity ---")
    perplexity_results = await run_perplexity_batch(
        competitor_claims, tag=tag, raw_results_path=RESULTS_DIR / f"benchmark_{tag}_perplexity_raw.jsonl",
    )

    print("\n--- Variant 6: Tavily + Gemini ---")
    tavily_gemini_results = await run_tavily_gemini_batch(
        competitor_claims, tag=tag, raw_results_path=RESULTS_DIR / f"benchmark_{tag}_tavily_gemini_raw.jsonl",
    )

    # --- scorecard ---
    print("\n" + "=" * 90)
    print("SCORECARD")
    print("=" * 90)

    by_claim_id = {c["claim_id"]: c for c in claims}
    scorecard = []

    def _find(results, claim_id):
        return next((r for r in results if r["claim_id"] == claim_id), None)

    for ac_row in ac_results:
        cid = ac_row["claim_id"]
        c = by_claim_id[cid]
        bm = _find(bare_model_results, cid)
        na = _find(nebius_agent_results, cid)
        gr = _find(generic_rag_results, cid)
        pp = _find(perplexity_results, cid)
        tg = _find(tavily_gemini_results, cid)
        row = {
            "claim_id": cid,
            "category": c["category"],
            "generated_by": c["generated_by"],
            "claim_text": c["claim_payload"]["text"],
            "ground_truth": c["ground_truth_verdict"],
            "ground_truth_note": c["ground_truth_note"],
            "ground_truth_sources": c["ground_truth_sources"],
            "anti_cassiopeia": {
                "predicted": ac_row["predicted_verdict"], "severity": ac_row["severity"], "confidence": ac_row["confidence"],
            },
            "competitors": {
                "bare_model": {"predicted": bm["predicted_verdict"], "severity": bm["severity"]} if bm else None,
                "nebius_agent": {"predicted": na["predicted_verdict"], "severity": na["severity"]} if na else None,
                "generic_rag": {"predicted": gr["predicted_verdict"], "severity": gr["severity"]} if gr else None,
                "perplexity": {"predicted": pp["predicted_verdict"], "severity": pp["severity"]} if pp else None,
                "tavily_gemini": {"predicted": tg["predicted_verdict"], "severity": tg["severity"]} if tg else None,
            },
        }
        scorecard.append(row)
        print(f"\n[{cid}] (category {c['category']}, generated_by={c['generated_by']})")
        print(f"  claim: {c['claim_payload']['text']}")
        print(f"  ground truth: {c['ground_truth_verdict']}")
        print(f"  Anti-Cassiopeia: {row['anti_cassiopeia']['predicted']} ({row['anti_cassiopeia']['severity']}, conf={row['anti_cassiopeia']['confidence']})")
        for name, res in row["competitors"].items():
            if res:
                print(f"    {name:15s}: {res['predicted']} ({res['severity']})")

    # --- budget report ---
    print("\n" + "=" * 90)
    print("BUDGET")
    print("=" * 90)
    print(f"Anti-Cassiopeia's own run: ${ac_tracker.total_cost_usd:.6f} "
          f"({ac_tracker.total_prompt_tokens} prompt / {ac_tracker.total_completion_tokens} completion tok, {ac_tracker.call_count} calls)")
    print(f"Nebius-billed competitors (bare_model+nebius_agent+generic_rag): ${nebius_tracker.total_cost_usd:.6f} "
          f"({nebius_tracker.call_count} calls), against this round's own ${ROUND2_NEBIUS_COMPETITOR_SUBCAP_USD:.2f} sub-cap")
    perplexity_cost = sum(r["cost_usd"] for r in perplexity_results)
    gemini_cost = sum(r["gemini_cost_usd"] for r in tavily_gemini_results)
    tavily_calls = sum(1 for r in tavily_gemini_results if r["predicted_verdict"] != "SKIPPED_QUOTA")
    print(f"Perplexity (free credits, real $ reported): ${perplexity_cost:.6f}")
    print(f"Tavily (free credits, call count): {tavily_calls} calls")
    print(f"Gemini (real $, separate provider): ${gemini_cost:.6f}")
    print(f"\nTotal Nebius this round: ${ac_tracker.total_cost_usd + nebius_tracker.total_cost_usd:.6f}")

    RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    raw_out.write_text(json.dumps({
        "mode": mode,
        "n_claims": len(claims),
        "scorecard": scorecard,
        "budget": {
            "anti_cassiopeia_usd": ac_tracker.total_cost_usd,
            "nebius_competitors_usd": nebius_tracker.total_cost_usd,
            "perplexity_usd": perplexity_cost,
            "gemini_usd": gemini_cost,
            "tavily_calls": tavily_calls,
        },
    }, indent=2, default=str))
    print(f"\nFull scorecard + budget written to {raw_out}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--mode", choices=["dryrun", "full"], default="dryrun")
    args = parser.parse_args()
    asyncio.run(main(args.mode))
